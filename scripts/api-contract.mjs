/**
 * Generated API contract: FastAPI/Pydantic → OpenAPI → TypeScript types.
 *
 *   npm run api:generate   export the OpenAPI document and regenerate the TS types
 *   npm run api:check      regenerate in memory; exit 1 if the committed files differ
 *
 * Both outputs are committed so contract changes are reviewable in a frontend diff, and
 * both are listed in .prettierignore: they are byte-for-byte generator output, and the
 * check compares bytes. Never edit them by hand.
 *
 * Needs `uv` on PATH. `--locked` makes a stale backend/uv.lock fail instead of silently
 * resolving different FastAPI/Pydantic versions, which could change the document.
 */
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const OPENAPI_PATH = "contracts/openapi.json";
const TYPES_PATH = "lib/api-client/generated/backend.ts";

const BANNER = `/**
 * GENERATED by \`npm run api:generate\` from ${OPENAPI_PATH}. Do not edit by hand.
 * The source of truth is the Pydantic schemas under backend/app/schemas.
 */

`;

function exportOpenApi() {
  return execFileSync(
    "uv",
    ["run", "--locked", "--directory", "backend", "python", "-m", "app.export_openapi"],
    { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  );
}

async function generate() {
  const openapi = exportOpenApi();
  const ast = await openapiTS(JSON.parse(openapi));
  return { [OPENAPI_PATH]: openapi, [TYPES_PATH]: BANNER + astToString(ast) };
}

async function readOrNull(path) {
  try {
    return await readFile(path, "utf8");
  } catch {
    return null;
  }
}

const mode = process.argv[2];
if (mode !== "generate" && mode !== "check") {
  console.error("usage: node scripts/api-contract.mjs <generate|check>");
  process.exit(2);
}

const outputs = await generate();

if (mode === "generate") {
  for (const [path, content] of Object.entries(outputs)) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
    console.log(`wrote ${path}`);
  }
} else {
  const stale = [];
  for (const [path, content] of Object.entries(outputs)) {
    if ((await readOrNull(path)) !== content) stale.push(path);
  }
  if (stale.length > 0) {
    console.error(`API contract drift — these files do not match the backend:`);
    for (const path of stale) console.error(`  ${path}`);
    console.error(`Run \`npm run api:generate\` and commit the result.`);
    process.exit(1);
  }
  console.log("API contract is up to date.");
}
